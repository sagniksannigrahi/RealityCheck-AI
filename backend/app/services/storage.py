"""Controlled media storage.

Objects are addressed by *opaque keys* (e.g. ``media/3f2a…e1.jpg``) generated by the server, never by
client-supplied paths. Keys are validated against a strict pattern and resolved inside the storage root,
so path traversal is impossible even if a malformed key reaches this layer. API responses expose only
HMAC-signed, expiring URLs for keys, never filesystem paths.
"""

from __future__ import annotations

import hashlib
import hmac
import re
import time
import uuid
from pathlib import Path
from typing import Protocol

KEY_RE = re.compile(r"^(media|crops|frames|reports)/[A-Za-z0-9_-]{1,64}(/[A-Za-z0-9_-]{1,64}){0,2}\.(jpg|jpeg|png|webp|gif|mp4|mov|webm|mkv|avi|json)$")


class StorageError(Exception):
    pass


def validate_key(key: str) -> str:
    if not isinstance(key, str) or ".." in key or key.startswith("/") or "\\" in key or not KEY_RE.match(key):
        raise StorageError("Invalid storage key.")
    return key


def new_key(prefix: str, ext: str, *parts: str) -> str:
    ext = ext.lower().lstrip(".")
    sub = "/".join(re.sub(r"[^A-Za-z0-9_-]", "", p)[:64] for p in parts if p)
    key = f"{prefix}/{sub + '/' if sub else ''}{uuid.uuid4().hex}.{ext}"
    return validate_key(key)


class StorageBackend(Protocol):
    name: str

    def put(self, key: str, data: bytes) -> None: ...

    def get(self, key: str) -> bytes: ...

    def exists(self, key: str) -> bool: ...

    def delete(self, key: str) -> None: ...

    def local_path(self, key: str) -> Path | None:
        """Filesystem path for decoders that need one (local backend only)."""
        ...


class LocalStorage:
    name = "local"

    def __init__(self, root: Path) -> None:
        self.root = Path(root).resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def _path(self, key: str) -> Path:
        validate_key(key)
        p = (self.root / key).resolve()
        if self.root != p and self.root not in p.parents:
            raise StorageError("Resolved path escapes the storage root.")
        return p

    def put(self, key: str, data: bytes) -> None:
        p = self._path(key)
        p.parent.mkdir(parents=True, exist_ok=True)
        tmp = p.with_suffix(p.suffix + ".tmp")
        tmp.write_bytes(data)
        tmp.replace(p)

    def get(self, key: str) -> bytes:
        p = self._path(key)
        if not p.is_file():
            raise StorageError("Object not found.")
        return p.read_bytes()

    def exists(self, key: str) -> bool:
        try:
            return self._path(key).is_file()
        except StorageError:
            return False

    def delete(self, key: str) -> None:
        p = self._path(key)
        if p.is_file():
            p.unlink()

    def local_path(self, key: str) -> Path | None:
        return self._path(key)

    def delete_prefix(self, prefix: str) -> int:
        if prefix not in {"media", "crops", "frames", "reports"} and not re.match(r"^(crops|frames)/[A-Za-z0-9_-]{1,64}$", prefix):
            raise StorageError("Invalid prefix.")
        base = (self.root / prefix).resolve()
        if self.root not in base.parents:
            raise StorageError("Invalid prefix.")
        n = 0
        if base.is_dir():
            for f in sorted(base.rglob("*"), reverse=True):
                if f.is_file():
                    f.unlink()
                    n += 1
                elif f.is_dir():
                    f.rmdir()
            base.rmdir()
        return n


class S3Storage:
    """Optional object-storage adapter (requires the ``s3`` extra / boto3). Not exercised in CI."""

    name = "s3"

    def __init__(self, bucket: str, endpoint_url: str | None = None) -> None:
        import boto3

        self._s3 = boto3.client("s3", endpoint_url=endpoint_url)
        self._bucket = bucket

    def put(self, key: str, data: bytes) -> None:
        self._s3.put_object(Bucket=self._bucket, Key=validate_key(key), Body=data)

    def get(self, key: str) -> bytes:
        try:
            return self._s3.get_object(Bucket=self._bucket, Key=validate_key(key))["Body"].read()
        except Exception as exc:  # noqa: BLE001
            raise StorageError("Object not found.") from exc

    def exists(self, key: str) -> bool:
        try:
            self._s3.head_object(Bucket=self._bucket, Key=validate_key(key))
            return True
        except Exception:  # noqa: BLE001
            return False

    def delete(self, key: str) -> None:
        self._s3.delete_object(Bucket=self._bucket, Key=validate_key(key))

    def local_path(self, key: str) -> Path | None:
        return None

    def delete_prefix(self, prefix: str) -> int:
        n = 0
        paginator = self._s3.get_paginator("list_objects_v2")
        for page in paginator.paginate(Bucket=self._bucket, Prefix=prefix + "/"):
            for obj in page.get("Contents", []):
                self._s3.delete_object(Bucket=self._bucket, Key=obj["Key"])
                n += 1
        return n


# ---------------------------------------------------------------------------------- signed URLs


def sign(key: str, owner: str, expires: int, secret: str) -> str:
    msg = f"{key}|{owner}|{expires}".encode()
    return hmac.new(secret.encode(), msg, hashlib.sha256).hexdigest()[:40]


def signed_query(key: str, owner: str, secret: str, ttl: int) -> str:
    exp = int(time.time()) + ttl
    return f"key={key}&owner={owner}&exp={exp}&sig={sign(key, owner, exp, secret)}"


def verify_signature(key: str, owner: str, exp: int, sig: str, secret: str) -> bool:
    if exp < int(time.time()):
        return False
    return hmac.compare_digest(sign(key, owner, exp, secret), sig)


_storage: StorageBackend | None = None


def get_storage() -> StorageBackend:
    global _storage
    if _storage is None:
        from app.core.config import get_settings

        s = get_settings()
        if s.storage_backend == "s3":
            if not s.s3_bucket:
                raise StorageError("RC_S3_BUCKET is required for the s3 storage backend.")
            _storage = S3Storage(s.s3_bucket, s.s3_endpoint_url)
        else:
            _storage = LocalStorage(s.storage_root)
    return _storage


def set_storage(st: StorageBackend | None) -> None:
    global _storage
    _storage = st
