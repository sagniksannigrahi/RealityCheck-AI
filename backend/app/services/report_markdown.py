"""Human-readable Markdown export of a verification report."""

from __future__ import annotations

from app.schemas.api import Report


def _esc(s: str | None) -> str:
    return (s or "").replace("|", "\\|").replace("\n", " ")


def report_to_markdown(rep: Report) -> str:
    j = rep.job
    lines = [
        "# RealityCheck AI — Verification Report",
        "",
        f"> {rep.disclaimer}",
        "",
        f"- **Job:** `{j.job_id}`",
        f"- **Status:** {j.status}  ·  **Mode:** {j.mode}  ·  **Media:** {j.media_type}",
        f"- **Created:** {j.created_at.isoformat()}  ·  **Finished:** {j.finished_at.isoformat() if j.finished_at else '—'}",
        f"- **Pipeline:** {j.pipeline_version}  ·  **Policy:** {j.policy}",
    ]
    if j.demo_mode:
        lines.append("- **DEMO MODE** — fake models; not a real evaluation.")
    if j.summary:
        lines += ["", f"**Summary:** {j.summary.get('headline', '')}"]
    lines += ["", "## Description", "", _esc(j.description_used) or "_(none)_"]
    if j.description_generated:
        lines += ["", "_This description was generated by a vision-language model and then verified independently._"]
    lines += ["", "## Claims", "", "| ID | Claim | Type | Verdict | Quality | Score | Review |", "|---|---|---|---|---|---|---|"]
    for c in rep.claims:
        r = c.result
        lines.append(
            f"| {c.claim.claim_id} | {_esc(c.claim.text)} | {c.claim.claim_type.value} | "
            f"{r.verdict if r else '—'} | {r.evidence_quality if r else '—'} | "
            f"{'' if not r or r.verification_score is None else f'{r.verification_score:+.2f}'} | "
            f"{'yes' if r and r.review_recommended else ''} |"
        )
    ev_by_id = {e.evidence_id: e for e in rep.evidence}
    lines += ["", "## Claim details"]
    for c in rep.claims:
        r = c.result
        if r is None:
            continue
        lines += ["", f"### {c.claim.claim_id}: {c.claim.text}", "", f"**{r.verdict}** — {r.explanation}"]
        if r.uncertainty_reasons:
            lines += ["", "Uncertainty:"] + [f"- {u}" for u in r.uncertainty_reasons]
        ev = [ev_by_id[i] for i in r.considered_evidence if i in ev_by_id]
        if ev:
            lines += ["", "| Source | Stance | Strength | Score | Time | Observation |", "|---|---|---|---|---|---|"]
            for e in ev:
                t = f"{e.timestamp_s:.2f}s" if e.timestamp_s is not None else ""
                sc = f"{e.raw_score:.2f}" if e.raw_score is not None else ""
                lines.append(f"| {e.source.value} | {e.stance.value} | {e.strength.value} | {sc} | {t} | {_esc(e.description)} |")
    if rep.frames:
        lines += ["", "## Sampled frames", "", "| Frame | Time (s) | Reason |", "|---|---|---|"]
        lines += [f"| {f.frame_index} | {f.timestamp_s:.2f} | {f.reason} |" for f in rep.frames]
    lines += ["", "## Models", "", "| Component | Model | Version | Device | Calls | Time (ms) | Demo | External |",
              "|---|---|---|---|---|---|---|---|"]
    for m in rep.model_executions:
        lines.append(f"| {m.component} | {m.model_name} | {m.model_version or ''} | {m.device or ''} | {m.calls} | "
                     f"{m.total_ms:.0f} | {'yes' if m.demo else ''} | {'yes' if m.external else ''} |")
    if rep.processing_errors:
        lines += ["", "## Processing errors", ""] + [f"- {e['stage']}: {e['error_type']} — {e['message']}"
                                                     for e in rep.processing_errors]
    lines += ["", f"_Generated {rep.generated_at.isoformat()}_", ""]
    return "\n".join(lines)
